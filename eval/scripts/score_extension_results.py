#!/usr/bin/env python3
"""Score extension baseline-vs-package-skill results with fixed rubrics."""

from __future__ import annotations

import argparse
import json
from collections import defaultdict
from pathlib import Path

try:
    from eval.scripts._bootstrap import bootstrap_repo_imports
except ModuleNotFoundError:
    from _bootstrap import bootstrap_repo_imports

bootstrap_repo_imports()

from eval.scripts.optimize_skills import load_jsonl, record_score
from eval.scripts.run_claude_eval import REPO_ROOT, load_tasks


DEFAULT_TASKS = REPO_ROOT / "eval" / "tasks" / "extension_tasks.json"
DEFAULT_RESULTS = REPO_ROOT / "eval" / "extension-results.jsonl"
DEFAULT_REPORT = REPO_ROOT / "eval" / "extension-score-report.md"
DEFAULT_SUMMARY = REPO_ROOT / "eval" / "extension-score-summary.json"


def score_records(tasks: list[dict], results: Path) -> dict[str, object]:
    task_by_id = {task["id"]: task for task in tasks}
    grouped: dict[tuple[str, str], dict[str, object]] = defaultdict(
        lambda: {"passed": 0, "total": 0, "tasks": []}
    )

    for record in load_jsonl(results):
        if record.get("status") != "ok":
            continue
        task = task_by_id.get(record.get("task_id"))
        if task is None:
            continue
        passed, total = record_score(task, record)
        key = (task["skill"], record["variant"])
        grouped[key]["passed"] = int(grouped[key]["passed"]) + passed
        grouped[key]["total"] = int(grouped[key]["total"]) + total
        grouped[key]["tasks"].append(
            {
                "task_id": task["id"],
                "split": task.get("split", ""),
                "passed": passed,
                "total": total,
                "score": passed / total if total else 0.0,
            }
        )

    rows = []
    for (skill, variant), values in sorted(grouped.items()):
        passed = int(values["passed"])
        total = int(values["total"])
        rows.append(
            {
                "skill": skill,
                "variant": variant,
                "score": passed / total if total else 0.0,
                "passed": passed,
                "total": total,
                "tasks": values["tasks"],
            }
        )

    decisions = []
    skills = sorted({row["skill"] for row in rows})
    for skill in skills:
        by_variant = {row["variant"]: row for row in rows if row["skill"] == skill}
        baseline = by_variant.get("baseline")
        package_skill = by_variant.get("package-skill")
        if baseline is None or package_skill is None:
            decision = "incomplete"
            delta = None
        else:
            delta = float(package_skill["score"]) - float(baseline["score"])
            if delta > 0:
                decision = "skill-win"
            elif delta < 0:
                decision = "baseline-win"
            else:
                decision = "tie"
        decisions.append({"skill": skill, "decision": decision, "delta": delta})

    return {"rows": rows, "decisions": decisions}


def write_report(payload: dict[str, object], report: Path, summary: Path) -> None:
    report.parent.mkdir(parents=True, exist_ok=True)
    summary.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")

    lines = [
        "# Extension Baseline-vs-Skill Score Report",
        "",
        "This report is generated by `eval/scripts/score_extension_results.py`.",
        "Scores use the same fixed keyword rubrics as the black-box optimizer.",
        "",
        "| Skill | Variant | Score | Passed | Total |",
        "| --- | --- | ---: | ---: | ---: |",
    ]
    for row in payload["rows"]:
        lines.append(
            f"| `{row['skill']}` | `{row['variant']}` | "
            f"{row['score']:.3f} | {row['passed']} | {row['total']} |"
        )
    lines.extend(["", "## Decisions", ""])
    for decision in payload["decisions"]:
        delta = decision["delta"]
        delta_text = "n/a" if delta is None else f"{delta:+.3f}"
        lines.append(
            f"- `{decision['skill']}`: {decision['decision']} "
            f"(package-skill minus baseline {delta_text})"
        )
    report.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--tasks", type=Path, default=DEFAULT_TASKS)
    parser.add_argument("--results", type=Path, default=DEFAULT_RESULTS)
    parser.add_argument("--report", type=Path, default=DEFAULT_REPORT)
    parser.add_argument("--summary", type=Path, default=DEFAULT_SUMMARY)
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args(argv)

    try:
        payload = score_records(load_tasks(args.tasks), args.results)
        write_report(payload, args.report, args.summary)
    except (OSError, ValueError) as exc:
        if args.json:
            print(json.dumps({"ok": False, "error": str(exc)}, indent=2))
        else:
            print(f"ERROR {exc}")
        return 1

    output = {"ok": True, **payload}
    if args.json:
        print(json.dumps(output, indent=2))
    else:
        print(f"Wrote score report to {args.report}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
